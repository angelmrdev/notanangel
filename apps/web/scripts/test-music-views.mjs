import assert from 'node:assert/strict';
import {musicView,hasDownload} from '../lib/music/views.mjs';
const now=new Date('2026-11-25');
const a={id:'a',category:'dj-edits',status:'published',publishedAt:'2026-11-20',downloads:[{enabled:true,rights:'authorized'}]};
const b={...a,id:'b',category:'dj-mixes',publishedAt:'2026-11-21',featured:true};
const c={...a,id:'c',category:'dj-sets',status:'draft'};
const d={...a,id:'d',publishedAt:'2026-11-26'};
const view=musicView([a,b,c,d],undefined,now);
assert.deepEqual(view.selected.map(r=>r.id),['b','a']);
assert.equal(view.featured.id,'b');
assert.deepEqual(view.groups.map(g=>g.category),['dj-edits','dj-mixes']);
assert.deepEqual(musicView([a,b], 'dj-edits',now).selected,[a]);
assert.equal(musicView([a,b], 'dj-edits',now).featured,undefined);
assert.equal(musicView([a],undefined,now).featured.id,'a');
assert.equal(musicView([],undefined,now).featured,undefined);
assert.equal(hasDownload(a),true);
assert.equal(hasDownload({...a,downloads:[{enabled:true,rights:'blocked'}]}),false);
assert.equal(hasDownload({...a,downloads:[]}),false);
console.log('Music view tests passed (10 assertions).');
