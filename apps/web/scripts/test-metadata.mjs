import assert from 'node:assert/strict';
import {readMetadata,writeMetadata,audioPayload} from '../lib/tools/metadata/core.mjs';
const mp3=Uint8Array.of(255,251,144,0,1,2,3,4);
const art={mime:'image/jpeg',data:Uint8Array.of(255,216,255,217)};
const tagged=writeMetadata(mp3,{title:'Mónica × Aitana',bpm:'128',key:'Am'},art);
assert.equal(readMetadata(tagged).tags.title,'Mónica × Aitana');
assert.equal(readMetadata(tagged).tags.bpm,'128');
assert.deepEqual(readMetadata(tagged).artwork,art);
assert.deepEqual(audioPayload(tagged),mp3);
const edited=writeMetadata(tagged,{title:'Nuevo',bpm:''},null);
assert.equal(readMetadata(edited).tags.key,'Am');
assert.equal(readMetadata(edited).tags.bpm,undefined);
assert.equal(readMetadata(edited).artwork,undefined);
assert.deepEqual(audioPayload(edited),mp3);
const wav=Uint8Array.from(Buffer.from('524946462800000057415645666d74201000000001000100401f0000803e000002001000646174610400000001020304','hex'));
const w=writeMetadata(wav,{title:'Prueba',artist:'DJ'});
assert.equal(readMetadata(w).tags.title,'Prueba');
assert.equal(readMetadata(w).properties.sampleRate,8000);
assert.deepEqual(audioPayload(w),audioPayload(wav));
assert.equal(readMetadata(writeMetadata(w,{title:''})).tags.artist,'DJ');
assert.equal(readMetadata(writeMetadata(w,{bpm:'128'})).tags.bpm,'128');
assert.deepEqual(readMetadata(writeMetadata(w,{},art)).artwork,art);
assert.throws(()=>readMetadata(new Uint8Array(10)));
assert.throws(()=>readMetadata(w.subarray(0,w.length-1)));
console.log('Metadata: 16 assertions passed (synthetic fixtures).');

const advanced=writeMetadata(w,{bpm:'128',key:'Am',remixer:'Not an Angel',comment:'Edición'},art);
assert.equal(readMetadata(advanced).tags.comment,'Edición');
assert.equal(readMetadata(advanced).tags.remixer,'Not an Angel');
assert.deepEqual(audioPayload(advanced),audioPayload(wav));
assert.equal(readMetadata(writeMetadata(advanced,{bpm:''},null)).tags.bpm,undefined);
assert.equal(readMetadata(writeMetadata(advanced,{},null)).artwork,undefined);
const v4=tagged.slice();v4[3]=4;
assert.equal(readMetadata(v4).tags.title,'Mónica × Aitana');
const v4edit=writeMetadata(v4,{year:'2026',title:'x'.repeat(200)});
assert.equal(readMetadata(v4edit).tags.year,'2026');
assert.equal(readMetadata(v4edit).tags.title,'x'.repeat(200));
assert.deepEqual(audioPayload(v4edit),mp3);
console.log('B2: 9 additional assertions passed');
